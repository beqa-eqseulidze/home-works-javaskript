const textData: string[] = [
    "hello", // პირველი წინადადება - შეიცავს 1 სიტყვას
    "Frontend Develpment", // მეორე წინადადება - შეიცავს 2 სიტყვას
    "I live in Georgia" // მესამე წინადადება - შეიცავს 4 სიტყვას
];

// ===================================================================================
// ფუნქცია პირველი: countWordsInSentences
// დანიშნულება: ითვლის სიტყვების რაოდენობას თითოეულ წინადადებაში
// პარამეტრი: sentences - წინადადებების მასივი (string[])
// დაბრუნება: რიცხვების მასივი (number[]), სადაც თითოეული რიცხვი არის სიტყვების რაოდენობა

function countWordsInSentences(sentences: string[]): number[] {
    // ვქმნით ცარიელ მასივს, სადაც ჩავწერთ თითოეული წინადადების სიტყვების რაოდენობას
    const wordCount: number[] = [];

    // for ციკლი - გადავდივართ ყველა წინადადებაზე ინდექსების მიხედვით
    // i = 0-დან ვიწყებთ, სანამ i ნაკლებია მასივის სიგრძეზე, ყოველ ნაბიჯზე i-ს ვზრდით 1-ით
    for (let i = 0; i < sentences.length; i++) {

        // sentences[i] - ვიღებთ წინადადებას i ინდექსზე
        // .split(" ") - ვყოფთ წინადადებას სიტყვებად, გამოყოფის საშუალებაა ინტერვალი (" ")
        // .length - ვითვლით რამდენი სიტყვა მივიღეთ გაყოფის შედეგად
        // wordCount.push() - ამ რიცხვს ვამატებთ wordCount მასივში
        wordCount.push(sentences[i].split(" ").length);
    }

    // ვაბრუნებთ სიტყვების რაოდენობების მასივს
    return wordCount;
}

// ===================================================================================
// ვამოწმებთ პირველი ფუნქციის მუშაობას
// ვიძახებთ countWordsInSentences ფუნქციას და არგუმენტად გადავცემთ textData მასივს

const result = countWordsInSentences(textData);

// console.log - ვბეჭდავთ ეკრანზე შედეგს
// "word count -" არის ტექსტი, რომელიც გვეტყვის რას ვბეჭდავთ
// result არის მასივი, რომელიც დაბრუნდა ფუნქციიდან - [1, 2, 4]
console.log("word count -", result);










// ===================================================================================
// ფუნქცია მეორე: filterSentences
// დანიშნულება: აბრუნებს წინადადებებს სიტყვების რაოდენობის მიხედვით
// პარამეტრი პირველი: sentences - წინადადებების მასივი (string[])
// პარამეტრი მეორე: isLong - ბულიანი მნიშვნელობა (true ან false)
//                  true - ვეძებთ გრძელ წინადადებებს 
//                  false - ვეძებთ მოკლე წინადადებებს
// პარამეტრი მესამე: limit - რიცხვი, რომელთან შედარებით ხდება ფილტრაცია
// დაბრუნება: გაფილტრული წინადადებების მასივი (string[])

function filterSentences(sentences: string[],
    isLong: boolean,
    limit: number): string[] {

    // ჯერ ვიძახებთ countWordsInSentences ფუნქციას, რომ მივიღოთ სიტყვების რაოდენობები
    // wordCount მასივი შეიცავს იგივე ინდექსებით სიტყვების რაოდენობას, როგორიც sentences მასივშია წინადადებები
    // მაგალითად: sentences[0] = "hello", wordCount[0] = 1
    const wordCount = countWordsInSentences(sentences);

    // ვქმნით ცარიელ მასივს, სადაც ჩავწერთ იმ წინადადებებს, რომლებიც ჩავარდება ფილტრში
    const filtered: string[] = [];

    // for ციკლი - გადავდივართ ყველა წინადადებაზე
    // i = 0-დან ვიწყებთ, სანამ i ნაკლებია მასივის სიგრძეზე
    for (let i = 0; i < sentences.length; i++) {

        // პირველი შემთხვევა: როცა isLong არის true
        // ეს ნიშნავს, რომ გვინდა გრძელი წინადადებები
        if (isLong) {

            // ვამოწმებთ: თუ სიტყვების რაოდენობა i ინდექსზე მეტია ან ტოლია limit-ზე
            // მაგალითად: limit = 3, wordCount[2] = 4, 4 >= 3 - true
            if (wordCount[i] >= limit) {

                // თუ პირობა შესრულდა, წინადადებას i ინდექსზე ვამატებთ filtered მასივში
                // sentences[i] - ვიღებთ წინადადებას i ინდექსზე
                // filtered.push() - ვამატებთ filtered მასივში
                filtered.push(sentences[i]);
            }


            
        // მეორე შემთხვევა: როცა isLong არის false
        // ეს ნიშნავს, რომ გვინდა მოკლე წინადადებები
        } else {

            // ვამოწმებთ: თუ სიტყვების რაოდენობა i ინდექსზე ნაკლებია limit-ზე
            // მაგალითად: limit = 3, wordCount[0] = 1, 1 < 3 - true
            if (wordCount[i] < limit) {

                // თუ პირობა შესრულდა, წინადადებას i ინდექსზე ვამატებთ filtered მასივში
                filtered.push(sentences[i]);
            }
        }
    }

    // ვაბრუნებთ გაფილტრულ წინადადებების მასივს
    return filtered;
}

// ===================================================================================
// პირველი ტესტირება: ვეძებთ გრძელ წინადადებებს (isLong = true)
// ვიძახებთ filterSentences ფუნქციას
// პირველი პარამეტრი: textData - წინადადებების მასივი
// მეორე პარამეტრი: true - ვეძებთ გრძელ წინადადებებს
// მესამე პარამეტრი: 3 - ვადგენთ ზღვარს, 3 ან მეტი სიტყვა

const longResult = filterSentences(textData, true, 3);

// console.log - ვბეჭდავთ შედეგს
// "long res -" არის ტექსტი, რომელიც გვეტყვის რას ვბეჭდავთ
// longResult არის მასივი, რომელიც დაბრუნდა - ["I live in Georgia"]
console.log("long res -", longResult);

// ===================================================================================
// მეორე ტესტირება: ვეძებთ მოკლე წინადადებებს (isLong = false)
// ვიძახებთ filterSentences ფუნქციას
// პირველი პარამეტრი: textData - წინადადებების მასივი
// მეორე პარამეტრი: false - ვეძებთ მოკლე წინადადებებს
// მესამე პარამეტრი: 3 - ვადგენთ ზღვარს, 3-ზე ნაკლები სიტყვა

const shortResult = filterSentences(textData, false, 3); 

// console.log - ვბეჭდავთ შედეგს
// "short res -" არის ტექსტი, რომელიც გვეტყვის რას ვბეჭდავთ
// shortResult არის მასივი, რომელიც დაბრუნდა - ["hello", "Frontend Develpment"]
console.log("short res -", shortResult);

// ===================================================================================
